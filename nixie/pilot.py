"""Pilot provisioning: users, 1:1 agent rooms (max 2 participants), per-user secrets.

A plan file lists the users and the rooms. For each user this writes
  <users_root>/<user>/agent.yaml   (no secrets; ${VAR} references only)
  <users_root>/<user>/secrets.env  (mode 600; owner token, ingest token, one token per room peer)
A room token is shared by the two agents of that room. Re-running keeps existing tokens.
"""

from __future__ import annotations

import secrets
from pathlib import Path
from typing import Any

import yaml

from .config import read_env_file
from .gateway import provision_user
from .sandbox import check_user

GATEWAY_ENV_KEYS = ("NIXIE_SESSION_SECRET", "NIXIE_PROXY_SECRET", "NIXIE_ADMIN_TOKEN", "NIXIE_BROWSER_POOL_TOKEN",
                    "OAUTH2_PROXY_COOKIE_SECRET")


class PlanError(ValueError):
    pass


def _peer_key(peer: str) -> str:
    return "PEER_TOKEN_" + peer.upper().replace("-", "_")


def load_plan(path: Path) -> dict[str, Any]:
    plan = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    users = plan.get("users") or []
    ids = [check_user(str(u["id"])) for u in users]
    if len(set(ids)) != len(ids):
        raise PlanError("duplicate user id")
    sso = [str(u.get("sso_user") or u["id"]) for u in users]
    if len(set(sso)) != len(sso):
        raise PlanError("duplicate sso_user")
    seen: set[frozenset[str]] = set()
    for room in plan.get("rooms") or []:
        if len(room) != 2:
            raise PlanError(f"a room has exactly 2 participants: {room}")
        a, b = (str(x) for x in room)
        if a == b or a not in ids or b not in ids:
            raise PlanError(f"bad room {room}: participants must be 2 different users from the plan")
        key = frozenset((a, b))
        if key in seen:
            raise PlanError(f"duplicate room {room}")
        seen.add(key)
    return plan


def provision(plan_path: Path, users_root: Path, gateway_url: str | None = None) -> dict[str, Any]:
    plan = load_plan(plan_path)
    if gateway_url:
        plan["gateway_url"] = gateway_url
    users = {str(u["id"]): u for u in plan["users"]}
    rooms = [tuple(str(x) for x in r) for r in plan.get("rooms") or []]
    gw = str(plan.get("gateway_url", "http://gateway:8080")).rstrip("/")
    scopes = list(plan.get("scopes") or ["availability", "meeting", "profile.trusted"])
    defaults = dict(plan.get("defaults") or {})
    root = Path(users_root)
    old = {u: read_env_file(root / u / "secrets.env") for u in users}

    peers: dict[str, list[str]] = {u: [] for u in users}
    room_token: dict[frozenset[str], str] = {}
    for a, b in rooms:
        peers[a].append(b)
        peers[b].append(a)
        room_token[frozenset((a, b))] = (old[a].get(_peer_key(b)) or old[b].get(_peer_key(a))
                                         or secrets.token_urlsafe(32))

    for uid, u in users.items():
        cfg: dict[str, Any] = {
            "agent_id": uid,
            "owner_name": u.get("name") or uid.capitalize(),
            "sso_user": str(u.get("sso_user") or uid),
            "owner_token": "${OWNER_TOKEN}",
            "ingest_token": "${INGEST_TOKEN}",
            "public_url": f"{gw}/u/{uid}",
            "timezone": plan.get("timezone", "Asia/Seoul"),
            "work_hours": plan.get("work_hours", [9, 18]),
            "facts": u.get("facts") or [],
            "peers": {p: {"url": f"{gw}/u/{p}", "token": "${" + _peer_key(p) + "}", "scopes": scopes,
                          "display_name": users[p].get("name") or p.capitalize()} for p in sorted(peers[uid])},
            **defaults,
        }
        env = {"OWNER_TOKEN": old[uid].get("OWNER_TOKEN") or secrets.token_urlsafe(32),
               "INGEST_TOKEN": old[uid].get("INGEST_TOKEN") or secrets.token_urlsafe(32)}
        for p in sorted(peers[uid]):
            env[_peer_key(p)] = room_token[frozenset((uid, p))]
        text = "# Secrets of this user only. Mounted only into this user's sandbox.\n" + \
            "".join(f"{k}={v}\n" for k, v in env.items())
        provision_user(root, uid, "# generated by `nixie pilot init`; edit the plan, then run it again\n"
                       + yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False), text)
    return {"users": sorted(users), "rooms": ["~".join(sorted(r)) for r in rooms]}


def ensure_gateway_env(env_file: Path) -> list[str]:
    """Add missing gateway secrets to the deploy env file. Existing values stay. Return the added keys."""
    env_file = Path(env_file)
    have = read_env_file(env_file)
    added = []
    lines = []
    for k in GATEWAY_ENV_KEYS:
        if not have.get(k):
            # oauth2-proxy needs a 32-byte cookie secret; token_urlsafe(24) gives 32 characters
            lines.append(f"{k}={secrets.token_urlsafe(24 if k == 'OAUTH2_PROXY_COOKIE_SECRET' else 32)}\n")
            added.append(k)
    if lines:
        env_file.parent.mkdir(parents=True, exist_ok=True)
        prev = env_file.read_text(encoding="utf-8") if env_file.exists() else ""
        if prev and not prev.endswith("\n"):
            prev += "\n"
        env_file.write_text(prev + "".join(lines), encoding="utf-8")
        env_file.chmod(0o600)
    return added
